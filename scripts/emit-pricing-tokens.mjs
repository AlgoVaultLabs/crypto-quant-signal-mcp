#!/usr/bin/env node
/**
 * emit-pricing-tokens.mjs — PRICING-FOLLOWUPS-GENERATOR-W1 CH3.
 *
 * Derives `ops/pricing-tokens.json` from the plan SoT so tutorial sources can carry
 * `{{PRICING.<key>}}` placeholders instead of hand-typed ladder literals.
 *
 * WHY (ruling G-B): the 7 exchange tutorials live in `algovault-skills` and render into this
 * repo's `landing/integrations/*.html`. CH7 of the previous wave fixed the RENDERED pages;
 * their SOURCES still said "100 calls/month", so the next `render-integrations` run would have
 * silently reverted it. Hand-syncing the literals resets that clock. Tokenizing retires the
 * class: a price or quota change becomes a token re-emit, and CH7's own 57-file sweep shrinks
 * to this file.
 *
 * Reads the COMPILED `dist/lib/plans.js` — the same dist-read `render-integrations.mjs`
 * already uses for `EXCHANGE_COUNT`, rather than parsing TypeScript. Run `npm run build` first.
 *
 * `--check` asserts committed == derived (the `snapshot_capabilities.mjs` pattern), so a plan
 * change that forgets the re-emit fails a gate instead of shipping stale tutorials.
 *
 * Verdict: exactly one terminal `PRICING_TOKENS_VERDICT=PASS|FAIL|INDETERMINATE`.
 * Exit: 0 = PASS · 1 = FAIL · 3 = INDETERMINATE.
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'ops', 'pricing-tokens.json');
const require_ = createRequire(import.meta.url);

const VERDICT = (tok, code) => { console.log(`PRICING_TOKENS_VERDICT=${tok}`); process.exit(code); };

let plans;
try {
  plans = require_(join(ROOT, 'dist', 'lib', 'plans.js'));
} catch {
  console.error('✗ dist/lib/plans.js not built — run `npm run build` first. Refusing to guess the ladder.');
  VERDICT('INDETERMINATE', 3);
}

const {
  PLANS, FREE_MONTHLY_CALLS, FREE_DAILY_CALLS, PREPAY_6MONTH_MONTHS,
  planCallsLabel, planDailyCallsLabel, planPriceLabel,
  planPrepayPriceLabel, planPrepayMonthlyEquivalent, planPrepaySavingsPct,
} = plans;

// Every value below is DERIVED. A literal here would just move the drift one file over.
const M = PREPAY_6MONTH_MONTHS;
const g = (n) => n.toLocaleString('en-US');

const tokens = {
  free_monthly: g(FREE_MONTHLY_CALLS),
  free_daily: g(FREE_DAILY_CALLS),
  /** The phrase tutorials actually use, composed once so nine files cannot compose it nine ways. */
  free_allowance: `${g(FREE_MONTHLY_CALLS)} calls/month (${g(FREE_DAILY_CALLS)}/day)`,
  starter_monthly: planCallsLabel('starter'),
  starter_daily: planDailyCallsLabel('starter') ?? '',
  starter_price: planPriceLabel('starter'),
  starter_prepay: planPrepayPriceLabel('starter', M) ?? '',
  starter_prepay_effective: planPrepayMonthlyEquivalent('starter', M) ?? '',
  starter_prepay_savings_pct: String(planPrepaySavingsPct('starter', M) ?? ''),
  pro_monthly: planCallsLabel('pro'),
  pro_daily: planDailyCallsLabel('pro') ?? '',
  pro_price: planPriceLabel('pro'),
  pro_prepay: planPrepayPriceLabel('pro', M) ?? '',
  pro_prepay_effective: planPrepayMonthlyEquivalent('pro', M) ?? '',
  pro_prepay_savings_pct: String(planPrepaySavingsPct('pro', M) ?? ''),
  prepay_months: String(M),
  /** R-A stated once. A tutorial that needs the sentence must not re-word it. */
  flat_billing: 'Every successful verdict counts against your allowance, HOLD included.',
  enterprise: 'Custom volume — contact us',
};

for (const [k, v] of Object.entries(tokens)) {
  if (typeof v !== 'string' || v === '') {
    console.error(`✗ token '${k}' derived empty — the plan SoT is missing a value this token needs.`);
    VERDICT('INDETERMINATE', 3);
  }
}

const payload = {
  _comment: [
    'GENERATED by scripts/emit-pricing-tokens.mjs from dist/lib/plans.js. Do not hand-edit.',
    'Consumed by scripts/render-integrations.mjs to substitute {{PRICING.<key>}} in tutorial',
    'sources (algovault-skills/docs/integrations/*.md + this repo docs/integrations/mcp-clients).',
    'A price or quota change is a re-emit here, not a sweep across every tutorial.',
  ],
  _source: 'src/lib/plans.ts (via dist/lib/plans.js)',
  tokens,
};
const next = JSON.stringify(payload, null, 2) + '\n';

if (process.argv.includes('--check')) {
  if (!existsSync(OUT)) {
    console.error(`✗ ${OUT} missing — run \`node scripts/emit-pricing-tokens.mjs\` and commit it.`);
    VERDICT('FAIL', 1);
  }
  const cur = readFileSync(OUT, 'utf8');
  if (cur !== next) {
    console.error('✗ ops/pricing-tokens.json is STALE vs the plan SoT.');
    console.error('  remediation: node scripts/emit-pricing-tokens.mjs && git add ops/pricing-tokens.json');
    const a = JSON.parse(cur).tokens ?? {}, b = tokens;
    for (const k of new Set([...Object.keys(a), ...Object.keys(b)])) {
      if (a[k] !== b[k]) console.error(`      ${k}: committed=${JSON.stringify(a[k])} derived=${JSON.stringify(b[k])}`);
    }
    VERDICT('FAIL', 1);
  }
  console.log(`✓ pricing tokens in sync with the plan SoT (${Object.keys(tokens).length} tokens).`);
  VERDICT('PASS', 0);
}

writeFileSync(OUT, next);
console.log(`✓ wrote ops/pricing-tokens.json (${Object.keys(tokens).length} tokens) — free ${tokens.free_allowance}`);
VERDICT('PASS', 0);
